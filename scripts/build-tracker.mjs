// Regenerates the screen tracker (docs/requirements/README.md) and the
// "Screens" section of each module doc from app/screens.js.
// Usage: node scripts/build-tracker.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(join(root, "app/screens.js"), "utf8"), sandbox);
const { modules, statuses, roles, flow } = sandbox.window.PINGME;

const icon = { todo: "⚪", reference: "🟠", design: "🔵", done: "🟢" };
const badge = (s) => `${icon[s]} ${statuses[s].label}`;
const all = modules.flatMap((m) => m.screens);
const count = (s) => all.filter((x) => x.status === s).length;
const byId = Object.fromEntries(all.map((s) => [s.id, s]));

// The app flow as a text tree (same data as the prototype's left panel).
function tree(nodes, pad = "") {
  return nodes
    .map((n, i) => {
      const last = i === nodes.length - 1;
      const via = n.via ? `[${n.via}] ` : "";
      const line = n.to
        ? `${pad}${last ? "└─" : "├─"} ${via}→ ${n.label || byId[n.to].name} (${n.to})`
        : `${pad}${last ? "└─" : "├─"} ${via}${byId[n.id].name} (${n.id}) ${icon[byId[n.id].status]}`;
      return [line, n.kids ? tree(n.kids, pad + (last ? "   " : "│  ")) : ""].filter(Boolean).join("\n");
    })
    .join("\n");
}

// Tracker
let out = `# Screen tracker

<!-- Generated by scripts/build-tracker.mjs from app/screens.js. Edit statuses there, then re-run. -->

Start with the [product overview](00-overview.md). Open \`index.html\` to browse the screens.

**${count("done")} of ${all.length} screens done** · ${Object.keys(statuses)
  .map((s) => `${badge(s)}: ${count(s)}`)
  .join(" · ")}

## App flow

Customers and vendors download the same app and use one account. After signing in, the app opens in **Customer mode** or **Vendor mode** (the one used last); Profile switches between them, and an account without a shop can add one. Screens marked *Both modes* show the version for the mode they were opened from.

\`\`\`text
${flow.map((sec) => `${sec.label}${sec.hint ? ` · ${sec.hint}` : ""}\n${tree(sec.kids)}`).join("\n\n")}
\`\`\`

`;
for (const role of roles) {
  out += `## ${role.label}\n\n`;
  for (const m of modules.filter((m) => m.role === role.id)) {
    const done = m.screens.filter((s) => s.status === "done").length;
    out += `### [${m.name}](${m.doc.replace("docs/requirements/", "")}) · ${done}/${m.screens.length}\n\n`;
    out += `| ID | Screen | Status | Reference |\n|---|---|---|---|\n`;
    for (const s of m.screens) {
      out += `| \`${s.id}\` | ${s.name} | ${badge(s.status)} | ${s.refs.length ? `${s.refs.length} image${s.refs.length > 1 ? "s" : ""}` : "–"} |\n`;
    }
    out += "\n";
  }
}
writeFileSync(join(root, "docs/requirements/README.md"), out);

// Module docs
const enc = (p) => "../../" + p.split("/").map(encodeURIComponent).join("/");
for (const m of modules) {
  const path = join(root, m.doc);
  const doc = readFileSync(path, "utf8");
  let body = "";
  for (const s of m.screens) {
    body += `\n### \`${s.id}\` ${s.name} · ${badge(s.status)}\n\n${s.summary}\n\n`;
    body += s.points.map((p) => `- ${p}`).join("\n") + "\n";
    if (s.notify?.length) body += `\n**Pings:**\n\n${s.notify.map((p) => `- ${p}`).join("\n")}\n`;
    if (s.criteria?.length) body += `\n**Acceptance:**\n\n${s.criteria.map((p) => `- [ ] ${p}`).join("\n")}\n`;
    if (s.note) body += `\n> ${s.note}\n`;
    if (s.refs.length) body += `\nReference: ${s.refs.map((r, i) => `[${i + 1}](${enc(r)})`).join(" · ")}\n`;
  }
  const next = doc.replace(
    /<!-- screens:start -->[\s\S]*<!-- screens:end -->/,
    `<!-- screens:start -->\n<!-- Generated from app/screens.js by scripts/build-tracker.mjs -->\n${body}\n<!-- screens:end -->`
  );
  writeFileSync(path, next);
}
console.log(`Tracker updated: ${all.length} screens in ${modules.length} modules.`);
